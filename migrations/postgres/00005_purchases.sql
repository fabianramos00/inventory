CREATE TABLE public.supplier_catalogs (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    product_id integer,
    provider_id integer,
    supplier_sku character varying(100),
    last_quoted_cost numeric(12,2) NOT NULL,
    lead_time integer
);


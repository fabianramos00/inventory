-- Sale payment ledger. The opening payment backfills the legacy cumulative
-- sales.amount_paid; sales.payment_method is no longer needed.

CREATE TABLE public.sale_payments (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    sale_id integer NOT NULL,
    amount numeric(12,2) NOT NULL,
    payment_method public.payment_method,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    created_by_id integer,
    CONSTRAINT ck_sale_payments_amount_positive CHECK (amount > 0),
    CONSTRAINT sale_payments_pkey PRIMARY KEY (id),
    CONSTRAINT sale_payments_sale_id_fkey FOREIGN KEY (sale_id)
        REFERENCES public.sales(id) ON DELETE CASCADE,
    CONSTRAINT sale_payments_created_by_id_fkey FOREIGN KEY (created_by_id)
        REFERENCES public.users(id)
);

INSERT INTO public.sale_payments (sale_id, amount, payment_method, created_at, created_by_id)
SELECT id, amount_paid, payment_method, COALESCE(created_at, now()), created_by_id
FROM public.sales
WHERE amount_paid > 0;

CREATE INDEX ix_sale_payments_sale_id_created_at_id
    ON public.sale_payments USING btree (sale_id, created_at, id);

ALTER TABLE public.sales DROP COLUMN payment_method;
